function mp = operation_params(job, tool_diameter, depth, feed_machine, feed_travel, feed_z)
% OPERATION_PARAMS Monta o MACHINE_PARAMS de uma operação.
%
%   MP = OPERATION_PARAMS(JOB, TOOL_DIAMETER, DEPTH, FEED_MACHINE,
%   FEED_TRAVEL, FEED_Z) junta a ferramenta, a profundidade e os avanços
%   (mm/min) da operação com o modelo da máquina (JOB.machine), com as
%   velocidades em mm/s. FEED_Z é o mergulho (padrão: FEED_MACHINE).

    if nargin < 6 || isempty(feed_z)
        feed_z = feed_machine;
    end

    if isfield(job.ncc, 'overlap_lines')
        overlap_lines = job.ncc.overlap_lines;
    else
        overlap_lines = job.ncc.overlap;
    end

    % Eixo Z limitado também por F_z
    modelo = job.machine.modelo;
    modelo.v_max_eixos(3) = min(modelo.v_max_eixos(3), job.machine.F_z);

    mp = struct( ...
        'tool_diameter',  tool_diameter, ...
        'overlap',        job.ncc.overlap, ...
        'overlap_lines',  overlap_lines, ...
        'contour_passes', job.ncc.contour_passes, ...
        'travel_height',  job.machine.travel_height, ...
        'depth',          depth, ...
        'eps',            modelo.eps_tcp, ...
        'F_cmd',          feed_machine / 60, ...
        'F_rapid',        feed_travel / 60, ...
        'F_z',            [job.machine.F_z, feed_z / 60], ...
        'A_max',          modelo, ...
        'verbose',        false);
end
