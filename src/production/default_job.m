function job = default_job()
% DEFAULT_JOB Configuração padrão de uma produção de PCI com PCB_CAM.
%
%   JOB = DEFAULT_JOB() devolve todos os campos usados por PCB_CAM com
%   valores padrão. Comprimentos em mm; avanços (feed_*) em mm/min.
%
%   Campos:
%     files.outline        - Gerber do contorno da placa (Edge Cuts).
%     files.top_copper     - Gerber do cobre superior ('' desativa).
%     files.bottom_copper  - Gerber do cobre inferior ('' desativa).
%     files.drills         - Cell array com zero ou mais arquivos .drl.
%     layers               - "top", "bottom" ou "both".
%     scale                - Conversão das coordenadas lidas (1000: m -> mm).
%     blank.size_x/size_y  - Placa virgem (obrigatório em "both").
%     blank.origin         - [x0 y0] do canto da área do recorte, ou "center".
%     blank.margin         - [mx my] margem da máquina (zero do G-code).
%     align.diameter       - Diâmetro dos furos de alinhamento ("both").
%     align.edge_margin    - Distância do centro dos furos às bordas
%                            (>= blank.margin).
%     ncc                  - Remoção de cobre: tool_diameter, overlap
%                            (contornos), overlap_lines (zigue-zague),
%                            contour_passes, z_engrave, feed_machine,
%                            feed_travel, feed_z.
%     mill                 - Recorte: tool_diameter, z_mill, feed_machine,
%                            feed_travel, feed_z.
%     holes                - Furos: tool_diameter, overlap, tolerance,
%                            feed_machine, feed_z ([] = valores de mill).
%     cut.offset_radius    - Offset do recorte (raio da fresa).
%     cut.tab_length       - Largura das abas (0 = sem abas).
%     cut.climb            - true: corte concordante.
%     machine              - F_z (mm/s), travel_height e modelo
%                            (MODELO_MAQUINA_PADRAO).
%     output               - dir, prefix, show_figures, save_figures e
%                            verbose.

    job.files.outline = '';
    job.files.top_copper = '';
    job.files.bottom_copper = '';
    job.files.drills = {};

    job.layers = "top";
    job.scale = 1000;

    job.blank.size_x = [];
    job.blank.size_y = [];
    job.blank.origin = [2 2];
    job.blank.margin = [5 5];

    job.align.diameter = 3.0;
    job.align.edge_margin = 6.5;

    job.ncc = struct( ...
        'tool_diameter',  0.2 - 1e-4, ...
        'overlap',        0.2, ...
        'overlap_lines',  0.2, ...
        'contour_passes', 3, ...
        'z_engrave',     -0.05, ...
        'feed_machine',   3000, ...
        'feed_travel',    3000, ...
        'feed_z',         900);

    job.mill = struct( ...
        'tool_diameter',  0.8, ...
        'z_mill',        -1.8, ...
        'feed_machine',   1000, ...
        'feed_travel',    3000, ...
        'feed_z',         300);

    job.holes = struct( ...
        'tool_diameter',  [], ...
        'overlap',        0.2, ...
        'tolerance',      0.05, ...
        'feed_machine',   [], ...
        'feed_z',         []);

    job.cut = struct( ...
        'offset_radius',  0.4, ...
        'tab_length',     2.0, ...
        'climb',          true);

    job.machine = struct( ...
        'F_z',            15.0, ...
        'travel_height',  1.0);
    job.machine.modelo = modelo_maquina_padrao();

    job.output = struct( ...
        'dir',            'out', ...
        'prefix',         'placa', ...
        'show_figures',   true, ...
        'save_figures',   true, ...
        'verbose',        true);
end
